import random  # Подключаем стандартный инструмент для генерации случайных чисел
import numpy as np  # Добавляем математическую библиотеку NumPy под коротким именем np

# Запрашиваем у пользователя количество строк и превращаем введенный текст в целое число
n = int(input("Введите N: "))
# Запрашиваем количество столбцов и точно так же переводим его в числовой формат
m = int(input("Введите M: "))

# Создаем пустой список, который станет контейнером для строк нашей таблицы
a = []
# Запускаем цикл, который повторится ровно N раз, создавая строку за строкой
for i in range(n):
    # Создаем временную пустую корзину для хранения чисел текущего ряда
    stroka = []
    # Запускаем внутренний цикл, который будет работать M раз, заполняя текущий ряд элементами
    for j in range(m):
        # Выбираем случайное целое число в диапазоне от 1 до 9 включительно
        num = random.randint(1, 9)
        # Кладим это сгенерированное случайное число в конец нашего текущего ряда
        stroka.append(num)
    # Помещаем полностью собранную и заполненную строку в главный контейнер таблицы
    a.append(stroka)

# Выводим на экран текстовый заголовок для первой таблицы
print("Матрица 1:")
# Запускаем цикл, который по очереди берет каждый ряд из нашей первой таблицы
for r in a:
    # Печатаем текущий ряд на экране, чтобы матрица выглядела наглядно и аккуратно
    print(r)

# Используем функцию библиотеки NumPy для зеркального переворота строк в столбцы
b = np.transpose(a)
# Выводим в консоль текстовое уведомление для перевернутого варианта
print("Транспонированная матрица:")
# Начинаем перебор всех рядов уже из новой, видоизмененной таблицы
for r in b:
    # Построчно выводим эту перевернутую структуру на экран компьютера
    print(r)

# Проверяем математическое условие: если высота таблицы не совпадает с ее шириной
if n != m:
    # Сообщаем пользователю, что для прямоугольных структур вычисление детерминанта невозможно
    print("Матрица не квадратная, определитель посчитать нельзя")
# Если же таблица имеет одинаковое количество строк и колонок, то выполняем код ниже
else:
    # Вычисляем детерминант первой таблицы встроенным модулем линейной алгебры и округляем результат
    o1 = round(np.linalg.det(a))
    # Считаем определитель для перевернутой таблицы и точно так же убираем погрешность округления
    o2 = round(np.linalg.det(b))
    # Показываем текстовую метку и итоговое целое число для первого определителя
    print("Определитель 1:", o1)
    # Демонстрируем текстовое описание и числовое значение для второго определителя
    print("Определитель 2:", o2)
    # Задаем программе вопрос: совпадает ли значение в первой переменной со значением во второй?
    if o1 == o2:
        # Если числа абсолютно одинаковые, выводим подтверждение их равенства в консоль
        print("Они равны")
    # Если бы по какой-то причине числа оказались разными, сработала бы эта ветка кода
    else:
        # Печатаем на экране вердикт о том, что результаты вычислений расходятся
        print("Не равны")